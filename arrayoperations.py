import numpy as np
x = np.array([1, 2, 3])
y = np.array([4, 5, 6])
 
# Element-wise operations
print("Addition:", x + y)
print("Subtraction:", x - y)
print("Multiplication:", x * y)
print("Division:", x / y)
 
# Universal functions
print("Square root:", np.sqrt(x))
print("Exponential:", np.exp(x))
print("Sin values:", np.sin(x))
